"""Export the model's ROM tables as $readmemh files for the RTL (checklist 7.1: generated inputs are committed,
with a header naming the generating script). Output: rtl/rom/*.hex

Usage: python -I scripts/export_roms.py          writes the files
       python -I scripts/export_roms.py --check  fails if the committed files differ from the model
Each file: one hex word per line, '//' header lines are legal for $readmemh.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from model import roms  # noqa: E402

OUT = os.path.join(ROOT, "rtl", "rom")
# name -> (table, hex digits, description)
TABLES = {
    "gamma_rom.hex": (roms.GAMMA_ROM, 2, "tone curve 255*x^0.4, index 0..1023 (Q10 of x), value u8"),
    "log2_rom.hex": (roms.LOG2_ROM, 4, "round(4096*log2(1+j/256)), j = 8-bit mantissa, value Q12 (13 bits)"),
    "exp2_rom.hex": (roms.EXP2_ROM, 5, "round(65536*2^(j/256)), j = 8-bit fraction, value Q16 (17 bits)"),
    "recip_rom.hex": (roms.RECIP, 5, "round(65536/n), index n = 0..9 (entry 0 unused), value Q16"),
    "motion_rom.hex": (roms.MOTION_F, 3, "motion index u (0..63) -> blend factor Q8 (0..256)"),
}


def render(name, table, digits, desc):
    lines = ["// %s -- GENERATED by scripts/export_roms.py from model/roms.py. Do not edit by hand." % name,
             "// %s" % desc,
             "// %d words" % len(table)]
    lines += [("%0" + str(digits) + "x") % v for v in table]
    return "\n".join(lines) + "\n"


# Verilog ROM modules (registered read, 1-clock latency) generated from the same tables: no $readmemh path issues
# between the simulator and Quartus (checklist 7.1). name -> (table, address bits, data bits)
VMODULES = {
    "rom_gamma":  (roms.GAMMA_ROM, 10, 8),
    "rom_log2":   (roms.LOG2_ROM, 8, 13),
    "rom_exp2":   (roms.EXP2_ROM, 8, 17),
    "rom_recip":  (roms.RECIP, 4, 17),
    "rom_motion": (roms.MOTION_F, 6, 9),
}


def render_v(name, table, aw, dw):
    lines = ["`timescale 1ns/1ps",
             "// %s.v -- GENERATED by scripts/export_roms.py from model/roms.py. Do not edit by hand." % name,
             "// %d x %d ROM, registered read: data is valid one clock after addr." % (1 << aw, dw),
             "module %s (input wire clk, input wire [%d:0] addr, output reg [%d:0] data);" % (name, aw - 1, dw - 1),
             "    always @(posedge clk) begin", "        case (addr)"]
    for i, v in enumerate(table):
        lines.append("            %d'd%d: data <= %d'd%d;" % (aw, i, dw, v))
    lines += ["            default: data <= %d'd0;" % dw, "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    bad = 0
    for name, (table, digits, desc) in TABLES.items():
        text = render(name, table, digits, desc)
        path = os.path.join(OUT, name)
        if check:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != text:
                print("DIFFERS:", path)
                bad += 1
        else:
            open(path, "w", newline="\n").write(text)
            print("wrote %s (%d words)" % (path, len(table)))
    for name, (table, aw, dw) in VMODULES.items():
        text = render_v(name, table, aw, dw)
        path = os.path.join(OUT, name + ".v")
        if check:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != text:
                print("DIFFERS:", path)
                bad += 1
        else:
            open(path, "w", newline="\n").write(text)
            print("wrote %s" % path)
    if check:
        print("rom check:", "FAIL" if bad else "ok")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
